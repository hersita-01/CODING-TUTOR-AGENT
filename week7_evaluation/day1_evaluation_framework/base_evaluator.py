from abc import ABC, abstractmethod
from typing import Any, Dict
from .models import EvaluationTestCase, EvaluationResult

class BaseEvaluator(ABC):
    """
    Abstract base class for all tutor evaluators.
    Day 3 (LLM Judge) and Day 4 (Metrics) will subclass this to implement specific 
    scoring algorithms (e.g. semantic similarity, LLM-as-a-judge).
    """
    
    @abstractmethod
    def evaluate(self, test_case: EvaluationTestCase, tutor_state: Dict[str, Any]) -> EvaluationResult:
        """
        Evaluate a single test case against the final LangGraph state generated by the tutor.
        
        Args:
            test_case: The input scenario and expected outcomes.
            tutor_state: The final State dictionary from the Week 6 graph execution.
            
        Returns:
            An EvaluationResult containing metrics, scores, and pass/fail status.
        """
        pass
        
    @abstractmethod
    def get_name(self) -> str:
        """Return the unique name of this evaluator."""
        pass
